_ACTIVE = STRINGS.get(LANGUAGE, STRINGS["en"])
# Per-request language (the panel's Accept-Language); None = the process language.
_REQUEST: contextvars.ContextVar[dict[str, str] | None] = contextvars.ContextVar(
    "foxprofile_lang", default=None
)


def current_language() -> str:
    return next(code for code, table in STRINGS.items() if table is _ACTIVE)


def set_language(code: str) -> None:
    """Switch the UI language for this process; callers rebuild their controls."""
    global _ACTIVE
    _ACTIVE = STRINGS.get(code, _ACTIVE)


@contextlib.contextmanager
def request_language(code: str) -> Iterator[None]:
    """Make get_string answer in `code` (if known) for the current request."""
    token = _REQUEST.set(STRINGS.get(code))
    try:
        yield
    finally:
        _REQUEST.reset(token)


def get_string(key: str, **kwargs: object) -> str:
    table = _REQUEST.get() or _ACTIVE
    text = table.get(key) or STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except KeyError:
            return text
    return text
